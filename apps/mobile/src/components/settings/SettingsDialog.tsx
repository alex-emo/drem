/** 粘贴 DeepSeek「导出所有历史对话」的华为云链接，服务端流式解压后逐会话写入。 */
const ArchiveImportCell = ({ disabled }: { disabled: boolean }) => {
  const [url, setUrl] = useState('')
  const [busy, setBusy] = useState(false)
  const [message, setMessage] = useState<string | null>(null)
  const [failed, setFailed] = useState(false)

  const run = async () => {
    const link = url.trim()
    if (!link.includes('myhuaweicloud.com')) {
      setFailed(true)
      setMessage('请粘贴 DeepSeek App 生成的华为云导出链接')
      return
    }
    setBusy(true)
    setFailed(false)
    setMessage('正在连接导出文件…')
    try {
      const skipIds = useChatStore.getState().sessions.map((session) => session.id)
      const stats = await importArchiveFromUrl(link, skipIds, (progress) => {
        setMessage(`已导入 ${progress.conversations} 个会话 / ${progress.messages} 条消息`)
      })
      setMessage(`已导入 ${stats.conversations} 个会话、${stats.messages} 条消息，跳过 ${stats.attachments} 个附件`)
      setUrl('')
      window.setTimeout(closeSettings, 1200)
    } catch (error) {
      setFailed(true)
      setMessage(error instanceof Error ? error.message : '导入失败')
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className={clsx(styles.cell, styles.importCell)}>
      <div className={styles.text}>
        <div className={styles.label}>从导出链接导入</div>
        <div className={clsx(styles.description, failed && styles.error)}>
          {message ?? '粘贴 DeepSeek「导出所有历史对话」生成的链接（华为云 OBS），支持几百 MB。'}
        </div>
      </div>
      <div className={styles.importActions}>
        <input
          value={url}
          disabled={disabled || busy}
          onChange={(event) => setUrl(event.target.value)}
          placeholder="https://...myhuaweicloud.com/...zip"
          className={styles.importInput}
        />
        <Button variant="outlined" size="m" disabled={disabled || busy} onClick={() => void run()}>
          {busy ? '导入中…' : '导入'}
        </Button>
      </div>
    </div>
  )
}

/** 粘贴 DeepSeek 分享链接，经 Dream Server 拉取后追加为一个新会话。 */
const ShareImportCell = ({ disabled }: { disabled: boolean }) => {
  const [url, setUrl] = useState('')
  const [busy, setBusy] = useState(false)
  const [message, setMessage] = useState<string | null>(null)
  const [failed, setFailed] = useState(false)

  const run = async () => {
    if (!isDeepSeekShare(url)) {
      setFailed(true)
      setMessage('请输入 chat.deepseek.com/share/... 链接')
      return
    }
    setBusy(true)
    setFailed(false)
    setMessage(null)
    try {
      const chat = await fetchSharedChat(url)
      await appendSession(buildShareSession(chat))
      setMessage(`已导入 ${chat.messages.length} 条消息${chat.attachments ? `，${chat.attachments} 个附件暂不支持` : ''}`)
      setUrl('')
      closeSettings()
    } catch (error) {
      setFailed(true)
      setMessage(error instanceof Error ? error.message : '导入失败')
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className={clsx(styles.cell, styles.row, styles.importCell)}>
      <div className={styles.text}>
        <div className={styles.label}>从分享链接导入</div>
        <div className={clsx(styles.description, failed && styles.error)}>
          {message ?? '粘贴 DeepSeek 分享链接，导入为一个新会话，不会覆盖现有聊天。'}
        </div>
      </div>
      <div className={styles.importActions}>
        <input
          value={url}
          disabled={disabled || busy}
          onChange={(event) => setUrl(event.target.value)}
          placeholder="https://chat.deepseek.com/share/..."
          className={styles.importInput}
        />
        <Button variant="outlined" size="m" disabled={disabled || busy} onClick={() => void run()}>
          {busy ? '导入中…' : '导入'}
        </Button>
      </div>
    </div>
  )
}

/** 将全部会话加密导出为 Dream 自有 .dream 文件。 */
const ExportHistory = ({ disabled }: { disabled: boolean }) => {
  const t = useTranslate()
  const empty = useChatStore((state) => state.sessions.length === 0)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState<Status>(null)

  const onExport = async () => {
    setBusy(true)
    setStatus(null)
    try {
      const { name, blob } = await exportDreamBackup()
      const url = URL.createObjectURL(blob)
      const link = document.createElement('a')
      link.href = url
      link.download = name
      link.click()
      setTimeout(() => URL.revokeObjectURL(url), 10_000)
    } catch (error) {
      setStatus(errorStatus('historyExportFailed', error))
    } finally {
      setBusy(false)
    }
  }

  return (
    <SettingCell
      label={t('exportAllLabel')}
      description={t('historyExportDescription')}
      status={status}
      action={
        <Button
          variant="outlined"
          size="m"
          className={styles.cellButton}
          disabled={disabled || busy || empty}
          onClick={() => void onExport()}
        >
          <IconDownloadOutline16 />
          {t('exportAllDownload')}
        </Button>
      }
    />
  )
}
